//! Vectors for `noir/lib/envelope`: an envelope sealed by `rust/eid-envelope`
//! over a synthetic DG1, which the Noir `seal` must reproduce.

use crate::bytes;
use crate::circuits::{Config, SAMPLE_COUNTRY, SAMPLE_EXPIRY};
use crate::mock::Doc;
use anyhow::Result;
use ark_ff::PrimeField;
use csca_registry::crypto::Hash;
use eid_envelope::{public_key, seal, Fr, Point, DG1_MAX, VIEWERS};
use std::fmt::Write as _;

/// Decimal string of a field element (Noir accepts it as a literal).
pub(crate) fn field(f: Fr) -> String {
    f.into_bigint().to_string()
}

/// Viewer secrets for the samples: slots 0 and 2 are used, 1 and 3 empty.
pub(crate) const VIEWER_SECRETS: [Option<u64>; VIEWERS] = [Some(1111), None, Some(2222), None];
pub(crate) const EPHEMERAL: u64 = 424_242;
pub(crate) const DATA_KEY: u64 = 777_777;
/// Sample binding context (stands in for a transfer identifier).
pub(crate) const CONTEXT: u64 = 31_337;

pub(crate) fn sample_viewers() -> [Point; VIEWERS] {
    VIEWER_SECRETS.map(|s| s.and_then(|s| public_key(Fr::from(s))))
}

fn point(p: Point) -> String {
    let (x, y) = p.unwrap_or_default();
    format!("EmbeddedCurvePoint {{ x: {}, y: {} }}", field(x), field(y))
}

fn padded(b: &[u8], n: usize) -> Vec<u8> {
    let mut v = b.to_vec();
    v.resize(n, 0);
    v
}

pub(crate) fn vectors() -> Result<String> {
    let doc = Doc::new(
        Config::Ecdsa {
            curve: "p256",
            hash: Hash::Sha256,
        },
        SAMPLE_COUNTRY,
        SAMPLE_EXPIRY,
    )?;
    let viewers = sample_viewers();
    let mut out = String::from(
        "// Generated by `eid-vectors envelope` with rust/eid-envelope. Do not edit.\n\n\
         use crate::{plaintext, seal};\n\
         use std::embedded_curve_ops::EmbeddedCurvePoint;\n\n",
    );
    let env = seal(
        &doc.dg1,
        &viewers,
        Fr::from(EPHEMERAL),
        Fr::from(DATA_KEY),
        Fr::from(CONTEXT),
    )
    .map_err(|e| anyhow::anyhow!("{e}"))?;
    // Viewers must be able to open it.
    for (slot, secret) in VIEWER_SECRETS.iter().enumerate() {
        if let Some(s) = secret {
            let dg1 = eid_envelope::open(&env, Fr::from(CONTEXT), slot, Fr::from(*s))
                .map_err(|e| anyhow::anyhow!("{e}"))?;
            anyhow::ensure!(dg1 == doc.dg1, "open failed");
        }
    }
    let list = |v: &[Fr]| v.iter().map(|f| field(*f)).collect::<Vec<_>>().join(", ");
    writeln!(
        out,
        "#[test]\nfn dg1_envelope() {{\n    let viewers = [{}];\n    let p = plaintext({}, {});\n    let env = seal(viewers, {EPHEMERAL}, {DATA_KEY}, {CONTEXT}, p);\n    assert_eq(env.ephemeral, {});\n    assert_eq(env.wrapped, [{}]);\n    assert_eq(env.ciphertext, [{}]);\n}}\n",
        viewers.iter().map(|v| point(*v)).collect::<Vec<_>>().join(", "),
        bytes(&padded(&doc.dg1, DG1_MAX)),
        doc.dg1.len(),
        point(Some(env.ephemeral)),
        list(&env.wrapped),
        list(&env.ciphertext),
    )?;
    Ok(out)
}
